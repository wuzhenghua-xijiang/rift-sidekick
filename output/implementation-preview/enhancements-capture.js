async page => {
  const url = 'http://127.0.0.1:4327/output/implementation-preview/enhancements.html';
  const checks = [], screenshots = [], errors = [];
  page.setDefaultTimeout(10000);
  page.on('pageerror', error => errors.push(error.message));
  const assert = (value, name) => { if (!value) throw new Error(name); checks.push(name); };
  const nav = name => page.getByRole('navigation', { name: '助手功能' }).getByRole('button', { name, exact: true });
  const capture = async name => {
    await page.evaluate(() => document.fonts.ready);
    const dimensions = await page.evaluate(() => { const el = document.querySelector('.content'); return { viewport: innerWidth, body: document.body.scrollWidth, content: el?.scrollWidth, available: el?.clientWidth }; });
    assert(dimensions.body <= dimensions.viewport && (!dimensions.available || dimensions.content <= dimensions.available), name + ': no horizontal overflow');
    await page.screenshot({ path: 'output/playwright/enhancements-' + name + '.png' });
    screenshots.push({ name, ...dimensions });
  };
  for (const width of [430, 390]) {
    await page.setViewportSize({ width, height: width === 430 ? 720 : 560 });
    const small = width === 390 ? '&size=minimum' : '';
    await page.goto(url + '?surface=dock' + small);
    await page.evaluate(() => localStorage.removeItem('rift-enhancement-example-pool'));
    await page.reload();
    await nav('战绩').click();
    await page.locator('.od-match-button').first().waitFor();
    await capture('history-' + width);
    await page.getByRole('button', { name: '近 50 场', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.od-match').length === 50);
    assert(await page.locator('.od-match').count() === 50, width + ': pagination produces 50 unique matches');
    await page.locator('.history-filter-fold > summary').click();
    await page.getByLabel('战绩模式筛选', { exact: true }).selectOption('mayhem');
    assert((await page.locator('.od-match').allTextContents()).every(text => text.includes('海克斯大乱斗')), width + ': mayhem filter excludes ordinary ARAM');
    await page.getByLabel('战绩胜负筛选', { exact: true }).selectOption('win');
    assert(await page.locator('.od-match.lost').count() === 0, width + ': result filter excludes defeats');
    await page.getByLabel('战绩分路筛选', { exact: true }).selectOption('support');
    await page.getByText('当前筛选没有对局', { exact: true }).waitFor();
    await page.getByRole('button', { name: '清除筛选', exact: true }).click();
    await page.locator('.history-filter-fold > summary').click();
    await page.locator('.history-performance > summary').click();
    await page.locator('.history-metrics').first().scrollIntoViewIfNeeded();
    await capture('performance-' + width);
    await page.locator('.history-performance > summary').click();
    await page.locator('.od-match-button').first().click();
    await page.getByRole('button', { name: '双方数据', exact: true }).waitFor();
    await page.locator('.history-detail').scrollIntoViewIfNeeded();
    await capture('review-' + width);
    await page.getByRole('button', { name: '双方数据', exact: true }).click();
    assert(await page.locator('.history-player').count() === 10, width + ': ten actual participants shown');
    await page.locator('.history-player > summary').first().click();
    await page.locator('.history-player').first().scrollIntoViewIfNeeded();
    assert((await page.locator('.history-player').first().textContent()).includes('闪现'), width + ': named spells and equipment load');
    await capture('players-' + width);
    await page.getByRole('button', { name: '时间线', exact: true }).click();
    await page.getByLabel('复盘时间点', { exact: true }).fill('10');
    await page.locator('.history-time-slider').scrollIntoViewIfNeeded();
    assert((await page.locator('.history-time-slider').textContent()).includes('10:00'), width + ': timeline slider selects a real frame');
    await page.getByLabel('只看本人参与', { exact: true }).check();
    assert((await page.locator('.history-events').textContent()).includes('本人阵亡'), width + ': local timeline event filter works');
    await capture('timeline-' + width);
    await page.getByRole('button', { name: '下载回放', exact: true }).click();
    assert(await page.evaluate(() => window.__riftCalls.some(call => call.name === 'replay' && call.input.action === 'download')), width + ': replay action uses selected game id');

    await nav('教练').click();
    await page.locator('.coach-pool > summary').click();
    await page.getByLabel('教练选人范围', { exact: true }).selectOption('custom');
    await page.getByLabel('搜索英雄池英雄', { exact: true }).fill('阿狸');
    await page.locator('.pool-candidates > button').first().click();
    await page.getByLabel('添加到英雄池分组', { exact: true }).selectOption('learningChampionIds');
    await page.getByLabel('搜索英雄池英雄', { exact: true }).fill('亚索');
    await page.locator('.pool-candidates > button').first().click();
    await page.getByRole('button', { name: '保存英雄池', exact: true }).click();
    await page.waitForFunction(() => window.__acceptanceState().coach.pool.mode === 'custom');
    assert(await page.evaluate(() => window.__acceptanceState().coach.pool.learningChampionIds.includes(157)), width + ': learning hero remains a separate preference');
    await page.locator('.pool-mode').scrollIntoViewIfNeeded();
    await capture('pool-' + width);
    await page.reload();
    await nav('教练').click();
    await page.locator('.coach-pool > summary').click();
    assert(await page.getByLabel('教练选人范围', { exact: true }).inputValue() === 'custom', width + ': saved pool survives reload');
    await page.getByLabel('教练选人范围', { exact: true }).selectOption('familiar');
    await page.evaluate(() => { window.__poolSaveFailure = true; });
    await page.getByRole('button', { name: '保存英雄池', exact: true }).click();
    await page.getByText('示例：英雄池保存失败，请重试。', { exact: true }).waitFor();
    assert(await page.evaluate(() => window.__acceptanceState().coach.pool.mode === 'custom'), width + ': failed pool save preserves effective scope');
    await page.evaluate(() => { window.__poolSaveFailure = false; });

    await page.goto(url + '?surface=dock&queue=2400&builds=fizz&hero=Fizz' + small);
    await page.getByRole('heading', { name: /^菲兹/ }).waitFor();
    await nav('对位').click();
    await page.locator('.aram-guide > summary').click();
    await page.locator('.augment-entry').first().waitFor();
    assert(await page.locator('.augment-entry').count() === 6, width + ': augment list is progressively disclosed');
    await page.locator('.augment-entry > summary').first().click();
    await page.locator('.augment-entry').first().scrollIntoViewIfNeeded();
    assert((await page.locator('.aram-guide').textContent()).includes('不是胜率'), width + ': performance is not presented as win rate');
    await capture('mayhem-' + width);
    await page.getByLabel('强化稀有度', { exact: true }).selectOption('silver');
    assert((await page.locator('.augment-entry > summary').allTextContents()).every(text => text.includes('白银')), width + ': rarity filter uses official metadata');
    await page.getByLabel('搜索海克斯强化', { exact: true }).fill('不存在的强化名');
    await page.getByText('当前筛选没有强化。', { exact: true }).waitFor();
    assert(true, width + ': augment empty search state is explicit');

    await page.goto(url + '?surface=dock&queue=450&builds=fizz&hero=Fizz' + small);
    await page.getByRole('heading', { name: /^菲兹/ }).waitFor();
    await nav('对位').click();
    await page.locator('.aram-guide > summary').click();
    await page.locator('.aram-balance').waitFor();
    assert(await page.locator('.augment-entry').count() === 0, width + ': ordinary ARAM never shows Mayhem augments');
    await capture('aram-' + width);
    await page.goto(url + '?surface=dock&cache=stale' + small);
    await page.locator('.recommend-cache').waitFor();
    await page.getByRole('button', { name: '应用方案', exact: true }).waitFor();
    assert(!await page.getByRole('button', { name: '应用方案', exact: true }).isEnabled(), width + ': stale offline plan cannot be applied');
    await page.locator('.recommend-cache').scrollIntoViewIfNeeded();
    await capture('offline-' + width);
    await page.goto(url + '?surface=dock&phase=postgame' + small);
    await page.locator('.champions-edition').waitFor();
    await capture('postgame-' + width);
    await page.locator('.postgame-history > summary').click();
    await page.getByRole('button', { name: '时间线', exact: true }).click();
    await page.locator('.history-timeline').waitFor();
    assert(true, width + ': postgame newspaper links to complete match timeline');
  }
  await page.goto(url + '?surface=dock&failure=timeline');
  await nav('战绩').click();
  await page.locator('.od-match-button').first().click();
  await page.getByRole('button', { name: '时间线', exact: true }).click();
  await page.getByRole('button', { name: '重试时间线', exact: true }).waitFor();
  assert((await page.locator('.history-detail').textContent()).includes('仍可查看结算详情与完整回放'), 'missing timeline keeps a factual fallback and retry');
  await page.goto(url + '?surface=dock&failure=aram');
  await page.getByRole('button', { name: '大乱斗', exact: true }).click();
  await nav('对位').click();
  await page.locator('.aram-guide > summary').click();
  await page.getByRole('button', { name: '重试资料', exact: false }).waitFor();
  assert(true, 'ARAM service failure has an actionable retry');
  for (const [width, height] of [[1100, 740], [840, 640]]) {
    await page.setViewportSize({ width, height });
    await page.goto(url + '?surface=login');
    await page.locator('.login-submit').waitFor();
    await capture('login-' + width);
  }
  assert(errors.length === 0, 'no renderer page errors');
  return { mode: 'Production React components, example match bridge and live Fizz ARAM snapshot, muted; no LCU or external model writes.', checks, screenshots, errors };
}
