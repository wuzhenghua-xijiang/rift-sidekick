async page => {
  const url = 'http://127.0.0.1:4327/output/implementation-preview/coach-audit.html';
  const checks = [], screenshots = [], errors = [];
  page.setDefaultTimeout(10000);
  page.on('pageerror', error => errors.push(error.message));
  const assert = (value, message) => { if (!value) throw new Error(message); checks.push(message); };
  const nav = name => page.getByRole('navigation', { name: '助手功能' }).getByRole('button', { name, exact: true });
  const generate = () => page.getByRole('button', { name: '生成建议', exact: true }).click();
  const capture = async name => {
    await page.evaluate(() => document.fonts.ready);
    const dimensions = await page.evaluate(() => {
      const el = document.querySelector('.content');
      return { viewport: innerWidth, body: document.body.scrollWidth, content: el?.scrollWidth, available: el?.clientWidth };
    });
    assert(dimensions.body <= dimensions.viewport && (!dimensions.available || dimensions.content <= dimensions.available), name + ': no horizontal overflow');
    const path = 'output/playwright/coach-audit-' + name + '.png';
    await page.screenshot({ path });
    screenshots.push({ path, ...dimensions });
  };
  const setCase = async name => {
    await page.evaluate(name => window.__coachAudit.setCase(name), name);
    await page.waitForFunction(() => !document.querySelector('.coach-analysis') && !document.querySelector('.coach-feedback.failure'));
    await nav('教练').click();
  };
  for (const [width, height] of [[430, 720], [390, 560]]) {
    const small = width === 390 ? '&size=minimum' : '';
    await page.setViewportSize({ width, height });
    await page.goto(url + '?surface=dock' + small);
    await nav('教练').click();
    await generate();
    await page.locator('.coach-analysis').waitFor();
    assert((await page.locator('.od-coach-call').textContent()).includes('保留金克丝'), width + ': current decision is visible');
    await page.getByRole('tab', { name: '阵容搭配', exact: true }).click();
    assert((await page.locator('.coach-composition-copy').textContent()).includes('优先承伤和保护'), width + ': real composition text is rendered');
    const team = await page.locator('.coach-composition .od-coach-picks').textContent();
    assert(team.includes('锤石') && team.includes('亚托克斯'), width + ': teammate suggestions remain usable');
    assert((await page.locator('.coach-visible-warnings > summary').textContent()).includes('已剔除冲突候选'), width + ': filtering is visible without opening evidence');
    await page.locator('.coach-composition').scrollIntoViewIfNeeded();
    await capture('team-' + width);
    await page.getByRole('tab', { name: 'Ban 推荐', exact: true }).click();
    assert(!(await page.locator('#coach-tab-panel').textContent()).includes('锤石'), width + ': a teammate candidate is not also recommended as a ban');
    await page.locator('.coach-controls > summary').click();
    assert(!await page.getByLabel('AI 教练分路', { exact: true }).isEnabled(), width + ': assigned live lane cannot be overridden by guide browsing');
    assert(await page.getByLabel('AI 教练分路', { exact: true }).inputValue() === 'adc', width + ': assigned ADC lane is authoritative');
    await page.locator('.coach-details > summary').click();
    assert((await page.locator('.coach-evidence-note').textContent()).includes('胜率排除未知胜负'), width + ': evidence names the real historical denominator');
    await page.locator('.coach-details').scrollIntoViewIfNeeded();
    await capture('evidence-' + width);
    await setCase('complete');
    await generate();
    await page.getByRole('tab', { name: '阵容点评', exact: true }).waitFor();
    assert(await page.locator('#coach-tab-panel .od-coach-picks').count() === 0, width + ': completed roster has no replacement recommendations');
    assert((await page.locator('.od-coach-call').textContent()).includes('仅按阵容估计：我方55%／敌方45%'), width + ': coarse estimate has its scope label');
    assert(await page.locator('.coach-composition-copy').isVisible(), width + ': final composition comparison is visible');
    await page.locator('.coach-composition').scrollIntoViewIfNeeded();
    await capture('final-' + width);
    await setCase('mayhem');
    await generate();
    await page.locator('.coach-analysis').waitFor();
    assert(await page.getByRole('tab', { name: 'Ban 推荐', exact: true }).count() === 0, width + ': Mayhem exposes no conventional ban tab');
    assert(await page.locator('.coach-composition .od-coach-picks').count() === 0, width + ': unknown Mayhem exchange pool produces no invented picks');
    assert((await page.locator('.coach-visible-warnings > summary').textContent()).includes('缺少已选强化'), width + ': missing augments are visible');
    assert(!(await page.locator('.od-coach-call').textContent()).includes('%'), width + ': Mayhem missing augments never gets a match estimate');
    await page.locator('.coach-composition').scrollIntoViewIfNeeded();
    await capture('mayhem-' + width);
    await setCase('mismatch');
    await generate();
    await page.locator('.coach-analysis').waitFor();
    const context = await page.evaluate(() => window.__coachAudit.contexts.at(-1));
    assert(context.patchNotes === null && context.laneStatistics === null, width + ': wrong-patch evidence never reaches the provider');
    assert((await page.locator('.coach-visible-warnings > summary').textContent()).includes('部分资料缺失或未采用'), width + ': mismatch explanation is visible');
    assert(!(await page.locator('.coach-analysis').textContent()).includes('这条旧版本变化'), width + ': unsupported patchImpact is dropped');
    await page.locator('.coach-visible-warnings').scrollIntoViewIfNeeded();
    await capture('mismatch-' + width);
    await setCase('unverified-odds');
    await generate();
    await page.getByRole('alert').waitFor();
    assert((await page.getByRole('alert').textContent()).includes('已拦截'), width + ': premature prediction becomes an actionable error');
    assert(await page.locator('.coach-analysis').count() === 0, width + ': rejected content is never rendered');
    await capture('rejected-' + width);
  }
  await setCase('late');
  await generate();
  await page.waitForFunction(() => window.__coachAudit.contexts.at(-1)?.draft.championLocked === false);
  await setCase('complete');
  await page.evaluate(() => window.__coachAudit.release());
  await page.getByRole('button', { name: '生成建议', exact: true }).waitFor();
  assert(await page.locator('.coach-analysis').count() === 0 && await page.getByRole('alert').count() === 0, 'late response from a changed draft is not rendered');
  assert(errors.length === 0, 'no renderer page errors');
  return { mode: 'Production coach service/parser and React components, synthetic responses only, muted; no online model calls or LCU writes.', checks, screenshots, errors };
}
